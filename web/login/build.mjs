#!/usr/bin/env node
// Builds web/login/bundle.js, the script of ntk.tools/login, from web/login/src/
// with esbuild. The rest of the site has no build step; only this page does,
// because it bundles the wallet connector (@hot-labs/near-connect).
//
//   cd web/login && npm ci && node build.mjs
//
// bundle.js is committed, so the server needs no Node packages. Both versions are
// pinned in package.json and package-lock.json; the same sources and versions give
// the same bytes, which web/test/login-bundle.test.mjs checks when node_modules exists.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import * as esbuild from 'esbuild';

const DIR = path.dirname(fileURLToPath(import.meta.url));
export const OUT = path.join(DIR, 'bundle.js');

function connectorVersion() {
  const pkg = path.join(DIR, 'node_modules', '@hot-labs', 'near-connect', 'package.json');
  return JSON.parse(fs.readFileSync(pkg, 'utf8')).version;
}

/** The bundle as text; `write` also puts it in bundle.js. */
export async function build({ write = true } = {}) {
  const banner = [
    '/* ntk.tools/login: built by web/login/build.mjs from web/login/src/ (do not edit this file).',
    ` * Includes @hot-labs/near-connect ${connectorVersion()}, MIT License, (c) HOT Labs,`,
    ' * https://github.com/azbang/near-connect. NTK code: MIT License, see LICENSE in the repository. */',
  ].join('\n');
  const result = await esbuild.build({
    entryPoints: [path.join(DIR, 'src', 'main.js')],
    bundle: true,
    format: 'iife',          // a classic script: document.currentScript gives the CSP nonce
    platform: 'browser',
    target: 'es2022',
    minify: true,
    legalComments: 'none',
    charset: 'utf8',
    banner: { js: banner },
    write: false,
    logLevel: 'silent',
  });
  const text = result.outputFiles[0].text;
  if (write) fs.writeFileSync(OUT, text);
  return text;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const text = await build();
  console.log(`web/login/bundle.js: ${(Buffer.byteLength(text) / 1024).toFixed(1)} KiB`);
}
